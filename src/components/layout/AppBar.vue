<script setup>
import { ref, computed } from 'vue'
import { useRouter } from 'vue-router'
import Breadcrumb from './Breadcrumb.vue'
import { useAuthStore } from '../../store/modules/auth'

const selectedLanguage = ref('Arabic')
const userMenu = ref(false)
const router = useRouter()
const authStore = useAuthStore()

const userName = computed(() => authStore.user?.name || 'مستخدم النظام')
const userEmail = computed(() => authStore.user?.email || '')

const languages = ['Arabic', 'English']

import { useLocale } from 'vuetify'

const { current } = useLocale()

// Props - استقبال حالة rail من الـ parent
const props = defineProps({
  rail: {
    type: Boolean,
    default: false
  }
})

// دالة toggle الـ sidebar - تُرسل event للـ parent
const emit = defineEmits(['toggle-sidebar'])

const toggleSidebar = () => {
  emit('toggle-sidebar')
}

const changeLanguage = (lang) => {
  console.log('Language changed to:', lang)
  selectedLanguage.value = lang
  if (lang === 'Arabic') {
    current.value = 'ar'
    document.documentElement.dir = 'rtl'
    document.documentElement.lang = 'ar'
  } else {
    current.value = 'en'
    document.documentElement.dir = 'ltr'
    document.documentElement.lang = 'en'
  }
}

const logout = () => {
  userMenu.value = false
  // مسح كل البيانات
  authStore.logout()
  localStorage.removeItem('auth_token')
  localStorage.removeItem('user')
  console.log('Logout done, redirecting...')
  // hard redirect
  window.location.href = '/login'
}

// Set initial direction
if (selectedLanguage.value === 'Arabic') {
  document.documentElement.dir = 'rtl'
  document.documentElement.lang = 'ar'
}
